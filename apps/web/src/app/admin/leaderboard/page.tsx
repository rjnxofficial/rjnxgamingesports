import { Gamepad2, Trophy } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Card } from "@/components/ui/card";
import { EmptyState, Table, TBody, TD, TH, THead, TR } from "@/components/ui/table";
import { AdminHeader, AdminPanel } from "@/components/admin/admin-shell";
import { ActionButton } from "@/components/dashboard/action-form";
import { ScoringRuleForm } from "./scoring-form";
import { requireStaff } from "@/server/auth";
import { recalculateLeaderboardAction, saveScoringRuleAction } from "@/server/actions/admin";
import { formatDate } from "@rjnx/shared";

export const dynamic = "force-dynamic";

type SearchParams = Promise<Record<string, string | string[] | undefined>>;

export default async function AdminLeaderboardPage({ searchParams }: { searchParams: SearchParams }) {
  const params = await searchParams;
  const selected = (Array.isArray(params.tournament) ? params.tournament[0] : params.tournament) ?? "";
  const session = await requireStaff("/admin/leaderboard");

  const [{ data: tournaments }, { data: rules }] = await Promise.all([
    session.supabase
      .from("tournaments")
      .select("id, name, status, format")
      .in("status", ["live", "registration_closed", "registration_open", "completed"])
      .order("starts_at", { ascending: false })
      .limit(60),
    session.supabase.from("scoring_rules").select("*").order("is_default", { ascending: false }),
  ]);

  const activeTournamentId = selected || (tournaments?.[0] as { id: string } | undefined)?.id || "";

  const { data: entries } = activeTournamentId
    ? await session.supabase
        .from("leaderboard_entries")
        .select("id, rank, total_points, total_kills, wins, matches_played, best_placement, team:teams(name), profile:profiles(username)")
        .eq("tournament_id", activeTournamentId)
        .order("rank", { ascending: true })
    : { data: [] as unknown[] };

  const ruleRows = (rules ?? []) as unknown as {
    id: string;
    name: string;
    placement_points: { placement: number; points: number }[];
    kill_points: number;
    bonus_rules: Record<string, number> | null;
    tie_breakers: string[];
    is_default: boolean;
  }[];

  return (
    <div className="space-y-6">
      <AdminHeader title="Leaderboards & scoring" subtitle="Configure scoring rules and recompute standings from verified results." />

      <AdminPanel
        title="Tournament standings"
        description="Entries are generated by the recalculate_leaderboard database function."
        actions={
          activeTournamentId ? (
            <ActionButton action={recalculateLeaderboardAction} fields={{ tournament_id: activeTournamentId }} label="Recalculate now" variant="outline" size="sm" />
          ) : null
        }
      >
        <form className="mb-3 flex flex-wrap items-end gap-2" action="/admin/leaderboard">
          <label htmlFor="tournament" className="font-display text-[10px] uppercase tracking-[0.18em] text-white/50">Tournament</label>
          <select
            id="tournament"
            name="tournament"
            defaultValue={activeTournamentId}
            className="h-9 min-w-56 rounded-md border border-white/10 bg-black/50 px-2 text-xs text-white"
          >
            {(tournaments ?? []).map((tournament) => (
              <option key={(tournament as { id: string }).id} value={(tournament as { id: string }).id}>
                {(tournament as { name: string }).name}
              </option>
            ))}
          </select>
          <button type="submit" className="h-9 rounded-md border border-white/10 px-3 font-display text-[10px] uppercase tracking-[0.16em] text-white/70 hover:border-rjnx-blue/40 hover:text-white">
            View
          </button>
        </form>

        {entries?.length ? (
          <Table>
            <THead>
              <TR>
                <TH>Rank</TH>
                <TH>Owner</TH>
                <TH>Matches</TH>
                <TH>Kills</TH>
                <TH>Wins</TH>
                <TH>Best</TH>
                <TH>Points</TH>
              </TR>
            </THead>
            <TBody>
              {(entries as unknown as {
                id: string;
                rank: number | null;
                total_points: number;
                total_kills: number;
                wins: number;
                matches_played: number;
                best_placement: number | null;
                team: { name: string } | null;
                profile: { username: string } | null;
              }[]).map((entry) => (
                <TR key={entry.id}>
                  <TD className="font-display text-xs text-white/60">#{entry.rank}</TD>
                  <TD className="text-white">{entry.team?.name ?? entry.profile?.username ?? "—"}</TD>
                  <TD className="text-white/60">{entry.matches_played}</TD>
                  <TD className="text-white/60">{entry.total_kills}</TD>
                  <TD className="text-white/60">{entry.wins}</TD>
                  <TD className="text-white/60">{entry.best_placement ?? "—"}</TD>
                  <TD className="font-display font-black text-rjnx-blue">{entry.total_points}</TD>
                </TR>
              ))}
            </TBody>
          </Table>
        ) : (
          <EmptyState icon={<Gamepad2 className="size-6" />} title="No standings yet" description="Verify match results, then recalculate to populate the leaderboard." />
        )}
      </AdminPanel>

      <AdminPanel title="Scoring rules" description="Placement points, kill points and tie-breakers used by the result engine.">
        <div className="grid gap-3 lg:grid-cols-2">
          {ruleRows.map((rule) => (
            <Card key={rule.id} className="p-4">
              <div className="flex items-center justify-between gap-2">
                <p className="font-display text-xs font-bold uppercase tracking-[0.1em] text-white">{rule.name}</p>
                {rule.is_default ? <Badge tone="pink">default</Badge> : <Badge tone="neutral">rule</Badge>}
              </div>
              <p className="mt-1 text-[10px] uppercase tracking-[0.14em] text-white/35">{rule.kill_points} pt / kill</p>
              <div className="mt-2 flex flex-wrap gap-1">
                {rule.placement_points.slice(0, 10).map((row) => (
                  <span key={row.placement} className="rounded bg-white/5 px-1.5 py-0.5 text-[10px] text-white/60">
                    #{row.placement}={row.points}
                  </span>
                ))}
              </div>
              <p className="mt-2 text-[10px] text-white/30">Tie-break: {rule.tie_breakers.join(" → ")}</p>
            </Card>
          ))}
        </div>

        <div className="mt-5 border-t border-white/[0.06] pt-4">
          <ScoringRuleForm action={saveScoringRuleAction} />
        </div>
      </AdminPanel>

      <p className="flex items-center gap-2 text-[10px] uppercase tracking-[0.16em] text-white/30">
        <Trophy className="size-3" /> Only verified results contribute points · last recalculated {formatDate(new Date())}
      </p>
    </div>
  );
}
